// node tests/regress.js — регрессия версии 1.6: случаи, найденные при проверке 1.5 (обход эвристик, падежи имён, ложные
// срабатывания на обычных словах, пересечение находок, нумерация людей в безопасной редакции).
// Набор написан после правок на тех же примерах, поэтому это защита от возврата ошибок, а не оценка качества.
const A = require('../assets/analyzer.js');
global.T = A.T;
const NER = require('../assets/ner.js');
require('./load-ner.js')(NER);
const ORDER = ['none', 'review', 'high', 'critical'];
const fails = [];
const run = (t, nn) => A.analyze(t, undefined, nn ? NER.findings(t) : null);

// Безопасные запросы: ни с правилами, ни с нейросетью не должно быть находок.
const SAFE = [
  'Максимум баллов за работу: 10. Составь критерии оценивания.',
  'Надежда — тоже слово. Напиши сочинение на тему «Вера в себя».',
  'Роман «Война и мир» написал Толстой, сделай краткий пересказ.',
  'Кириллица и глаголица: объясни различия для 5 класса.',
  'Владеть иностранным языком — важный навык. Составь тест.',
  'Платон и Аристотель: сравни философские взгляды.',
  'Я роман читал вчера. Помоги написать отзыв.',
  'Нина купила 5 яблок, Рита — 3. Сколько яблок у девочек?',
  'Сформулируй цели урока литературы по роману «Мастер и Маргарита».',
  'Напиши рассказ о мальчике Иване, который любит футбол.',
  'Составь план урока для 6 класса по теме «Дроби».',
  'Напиши сочинение про Александра Пушкина и Анну Ахматову'
];
for (const t of SAFE)
  for (const nn of [false, true]) {
    const r = run(t, nn);
    if (r.level !== 'none')
      fails.push(
        `Ложная тревога (${nn ? 'с нейросетью' : 'правила'}) [${r.level}]: ${t} → ${r.f.map((x) => x.ty + ':' + x.txt).join(', ')}`
      );
  }

// Рискованные запросы: [текст, минимальный уровень, [тип:фрагмент, ...]]. Проверяются правила без нейросети.
const RISK = [
  [
    'Составь по теме «поддержка» рекомендации для девочки из 5 класса с диагнозом аутизм, мать пьёт, отец сидит.',
    'high',
    ['HEALTH:аутизм', 'FAMILY:отец сидит']
  ],
  ['Помоги написать характеристику ученику Диме, у него диагноз аутизм.', 'critical', ['NAME:Диме']],
  ['У Маши в 5 классе диагноз диабет, как организовать питание?', 'high', ['NAME:Маши']],
  ['Расскажи, как помочь Коле: диагноз эпилепсия, мать пьёт.', 'critical', ['NAME:Коле']],
  ['Кузьменко Дмитрий, 2009 года рождения, ученик 8А', 'high', ['DOB:2009 года рождения']],
  ['Живёт по адресу Садовая 7 кв 3', 'high', ['ADDR:Садовая 7 кв 3']],
  ['пишите ivan (собака) mail.ru', 'high', ['EMAIL:mail.ru']],
  ['api key: AbCdEf123456', 'high', ['SECRET:AbCdEf123456']],
  ['Он написал в чате, что возьмёт нож в школу', 'high', ['CRISIS:нож']],
  ['Напиши характеристику на Кузьменко Д.А., ученик 8А', 'review', ['NAME:Кузьменко Д.А.', 'TMPL:характеристику']],
  ['Ученик из гимназии 5 Минска, 8А, мама работает в ПДН', 'review', ['SCHOOL:гимназии 5']],
  ['У девочки из 4В ВИЧ, родители скрывают. Как организовать физкультуру?', 'high', ['HEALTH:ВИЧ']],
  ['Мой сосед по парте Влад бьёт меня и забирает деньги', 'high', ['CRISIS:бьёт меня']],
  ['Классный руководитель Иванова А. П. просит прислать список', 'review', ['NAME:А. П.']],
  ['привет, я иван петров, пиши мне на почту ivan собака mail точка by', 'high', ['NAME:иван петров']],
  ['Составь памятку для родителей о профилактике депрессии у подростков.', 'review', ['HEALTH:депресс']],
  ['Что такое депрессия? Объясни простыми словами для урока ОБЖ.', 'review', ['HEALTH:депресс']]
];
for (const [t, min, must] of RISK) {
  const r = run(t, false);
  if (ORDER.indexOf(r.level) < ORDER.indexOf(min)) fails.push(`Уровень ${r.level} ниже ${min}: ${t}`);
  for (const m of must) {
    const [ty, frag] = m.split(/:(.*)/s);
    if (!r.f.some((x) => x.ty === ty && x.txt.includes(frag)))
      fails.push(`Не найдено ${m} в «${t}» (есть: ${r.f.map((x) => x.ty + ':' + x.txt).join(', ') || '—'})`);
  }
}

// Редакция: имя в безопасном варианте не остаётся, разные люди получают разные номера, одно имя в разных падежах — один номер.
{
  const t = 'Иван Петров и Мария Сидорова пришли. Ивана Петрова вызвали, а Мария ушла.';
  const r = run(t, false),
    s = A.safeText(t, r.f);
  if (/Петров|Сидоров|Иван|Мария/.test(s)) fails.push('В редакции остались имена: ' + s);
  if (!s.includes('[человек 1]') || !s.includes('[человек 2]')) fails.push('Нет нумерации людей: ' + s);
  if ((s.match(/\[человек 1\]/g) || []).length < 2)
    fails.push('Падежные формы одного имени получили разные номера: ' + s);
  const one = 'Составь характеристику ученика Ивана Петрова.',
    s1 = A.safeText(one, run(one, false).f);
  if (/\[человек \d\]/.test(s1)) fails.push('Один человек не должен получать номер: ' + s1);
}

// Пересечения: слабая находка (шаблон) не должна «съедать» имя, а отброшенное известное имя не должно оставлять обрывков.
{
  const r = run('Напиши характеристику на Кузьменко Д.А.', false);
  if (!r.f.some((x) => x.ty === 'NAME') || !r.f.some((x) => x.ty === 'TMPL'))
    fails.push('Шаблон и имя должны находиться вместе');
  const k = run('Составь тест о Пушкине и Лермонтове для 9 класса', false);
  if (k.f.some((x) => x.ty === 'NAME')) fails.push('Известные деятели помечены как люди');
}
if (fails.length) {
  console.error('Регрессия 1.6: ОШИБКИ\n  ' + fails.join('\n  '));
  process.exit(1);
}
console.log(`Регрессия 1.6: ок (${SAFE.length} безопасных × 2, ${RISK.length} рискованных, редакция, пересечения)`);
