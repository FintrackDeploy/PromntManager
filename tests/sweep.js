const bad = [];
let hit = 0;
for (const [t, ty, frag] of MUST) {
  const r = A.analyze(t);
  const ok = r.f.some((x) => x.ty === ty && x.txt.toLowerCase().includes(frag.toLowerCase()));
  if (ok) hit++;
  else
    bad.push(
      `ПРОПУСК ${ty} «${frag}» в «${t}» → ${r.f.map((x) => x.ty + ':' + x.txt).join(' | ') || 'пусто'} [${r.level}]`
    );
}

let clean = 0;
for (const t of SAFE) {
  const r = A.analyze(t);
  const risky = r.f.filter((x) => !['CLASS', 'SCHOOL', 'LOC', 'ORG', 'TMPL'].includes(x.ty));
  if (r.level === 'none' || (r.level === 'review' && risky.length === 0)) clean++;
  else
    bad.push(
      `ЛОЖНОЕ «${t}» → ${r.level}: ${r.f.map((x) => x.ty + ':' + x.txt).join(' | ') || 'только предупреждения'}`
    );
}

// После редакции сильные идентификаторы не должны остаться в тексте.
const REDACT = [
  'Позвони +375291112233 и напиши на pupil@school.by, личный номер 3140585A012PB4',
  'Пароль от дневника qwerty12, телеграм @pupil_2012, адрес вул. Савецкая 12'
];
