let bad = [];
for (const [t, ty, frag] of MUST) {
  const r = A.analyze(t);
  if (!r.f.some((x) => x.ty === ty && x.txt.includes(frag)))
    bad.push(`не найдено ${ty} «${frag}» в «${t}» (есть: ${r.f.map((x) => x.ty + ':' + x.txt).join(', ') || '—'})`);
}
for (const t of NOT) {
  const r = A.analyze(t);
  const f = r.f.filter((x) => !['IP'].includes(x.ty));
  if (f.length && !/пинг/.test(t))
    bad.push(`ложное срабатывание в «${t}»: ${f.map((x) => x.ty + ':' + x.txt).join(', ')}`);
}
// безопасная редакция не должна оставлять хвост найденного
const r = A.analyze('Алесь Мельнік');
const sf = A.safeText('Алесь Мельнік', r.f);
if (/ік|Мельн/.test(sf)) bad.push('в безопасной редакции остался хвост фамилии: ' + sf);
console.log(`Детекторы: ${MUST.length} обязательных и ${NOT.length} запрещённых срабатываний проверено`);
if (bad.length) {
  console.error(bad.join('\n'));
  process.exit(1);
}
